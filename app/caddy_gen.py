import logging
import subprocess
from pathlib import Path

from sqlalchemy.orm import Session

from app.config import settings
from app.models import CustomDomain, Organization

logger = logging.getLogger("dyergate.caddy")
CADDYFILE = Path("/etc/caddy/Caddyfile")


def regenerate_caddyfile(db: Session) -> str:
    """Build a fresh Caddyfile from DB state. Reloads Caddy if present."""
    lines = [
        f"# Auto-generated by DyerGate — do not edit",
        f"{settings.PLATFORM_DOMAIN} {{",
        "  reverse_proxy 127.0.0.1:8080",
        "}",
        "",
    ]

    orgs = db.query(Organization).filter(Organization.is_active == True).all()
    for o in orgs:
        lines.append(f"{o.slug}.{settings.PLATFORM_DOMAIN} {{")
        lines.append("  reverse_proxy 127.0.0.1:8080")
        lines.append("}")
        lines.append("")

    custom = db.query(CustomDomain).filter(
        CustomDomain.verified_at.isnot(None),
        CustomDomain.ssl_status != "failed",
    ).all()
    for cd in custom:
        lines.append(f"{cd.domain} {{")
        lines.append("  reverse_proxy 127.0.0.1:8080")
        lines.append("}")
        lines.append("")

    body = "\n".join(lines)
    try:
        CADDYFILE.parent.mkdir(parents=True, exist_ok=True)
        CADDYFILE.write_text(body)
        subprocess.run(["systemctl", "reload", "caddy"], check=False, capture_output=True)
        logger.info("Caddyfile regenerated with %d orgs, %d custom domains", len(orgs), len(custom))
    except Exception as e:
        logger.exception("caddy reload failed: %s", e)
    return body
